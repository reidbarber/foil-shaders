import fs from "node:fs";
import { specs } from "./preset-specs.mjs";

const shaderTypesPath = "Sources/FoilShaders/ShaderTypes.swift";
const outPath = "Sources/FoilShaders/ComponentInitializers.swift";
const shaderTypes = fs.readFileSync(shaderTypesPath, "utf8");

function matchingBraceEnd(text, openIndex) {
  let depth = 0;
  for (let i = openIndex; i < text.length; i++) {
    if (text[i] === "{") depth++;
    if (text[i] === "}") {
      depth--;
      if (depth === 0) return i + 1;
    }
  }
  throw new Error("Unclosed brace");
}

function matchingParenEnd(text, openIndex) {
  let depth = 0;
  for (let i = openIndex; i < text.length; i++) {
    if (text[i] === "(") depth++;
    if (text[i] === ")") {
      depth--;
      if (depth === 0) return i;
    }
  }
  throw new Error("Unclosed parenthesis");
}

function splitTopLevelCommas(text) {
  const parts = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    if (char === "(" || char === "[" || char === "<") depth++;
    if (char === ")" || char === "]" || char === ">") depth--;
    if (char === "," && depth === 0) {
      parts.push(text.slice(start, i));
      start = i + 1;
    }
  }
  parts.push(text.slice(start));
  return parts.map((part) => part.trim()).filter(Boolean);
}

function structBlock(name) {
  const re = new RegExp(`public\\s+struct\\s+${name}(?:\\s*:[^{]+)?\\s*\\{`);
  const match = shaderTypes.match(re);
  const start = match?.index ?? -1;
  if (start < 0) throw new Error(`Missing ${name}`);
  return shaderTypes.slice(start, matchingBraceEnd(shaderTypes, shaderTypes.indexOf("{", start)));
}

function paramsFor(paramsType) {
  const block = structBlock(paramsType);
  const token = "public init(";
  const initStart = block.indexOf(token);
  if (initStart < 0) throw new Error(`Missing public init for ${paramsType}`);
  const open = block.indexOf("(", initStart);
  const close = matchingParenEnd(block, open);
  return splitTopLevelCommas(block.slice(open + 1, close)).map((param) => {
    const withoutDefault = param.split(/\s=\s/)[0].trim();
    const match = withoutDefault.match(/^([A-Za-z][A-Za-z0-9_]*):\s*(.+)$/);
    if (!match) throw new Error(`Could not parse parameter "${param}" in ${paramsType}`);
    return { name: match[1], type: match[2].trim() };
  });
}

const sizingParams = [
  ["fit", "ShaderFit"],
  ["scale", "Float"],
  ["rotation", "Float"],
  ["originX", "Float"],
  ["originY", "Float"],
  ["offsetX", "Float"],
  ["offsetY", "Float"],
  ["worldWidth", "Float"],
  ["worldHeight", "Float"],
];

const motionParams = [
  ["speed", "Float"],
  ["frame", "Float"],
];

const renderOptionParams = [
  ["minPixelRatio", "Float"],
  ["maxPixelCount", "Int"],
];

function parameterLine(defaultPreset, param) {
  return `    ${param.name}: ${param.type} = ${defaultPreset}.params.${param.name},`;
}

function generatedInitializer(spec) {
  const params = paramsFor(spec.paramsType);
  const defaultPreset = `${spec.presetType}.default`;
  const lines = [
    `extension ${spec.viewName ?? spec.componentName} {`,
    "  public init(",
    ...params.map((param) => parameterLine(defaultPreset, param)),
    ...sizingParams.map(
      ([name, type]) => `    ${name}: ${type} = ${defaultPreset}.sizing.${name},`
    ),
    ...motionParams.map(
      ([name, type]) => `    ${name}: ${type} = ${defaultPreset}.motion.${name},`
    ),
    ...renderOptionParams.map(
      ([name, type]) => `    ${name}: ${type} = ${defaultPreset}.renderOptions.${name},`
    ),
    `    image: ShaderImage? = ${defaultPreset}.image`,
    "  ) {",
    "    self.init(",
    `      params: ${spec.paramsType}(`,
    ...params.map((param, index) => {
      const comma = index === params.length - 1 ? "" : ",";
      return `        ${param.name}: ${param.name}${comma}`;
    }),
    "      ),",
    "      sizing: ShaderSizingParams(",
    "        fit: fit, scale: scale, rotation: rotation, originX: originX, originY: originY,",
    "        offsetX: offsetX, offsetY: offsetY, worldWidth: worldWidth, worldHeight: worldHeight),",
    "      motion: ShaderMotionParams(speed: speed, frame: frame),",
    "      renderOptions: ShaderRenderOptions(",
    "        minPixelRatio: minPixelRatio, maxPixelCount: maxPixelCount),",
    "      image: image",
    "    )",
    "  }",
    "}",
  ];
  return lines.join("\n");
}

const output = [
  "// Generated by Scripts/generate-swift-component-initializers.mjs.",
  specs.map(generatedInitializer).join("\n\n"),
  "",
].join("\n");

fs.writeFileSync(outPath, output);
